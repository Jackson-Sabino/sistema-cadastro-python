import json
import os

# Carrega os clientes se o arquivo já existir
ARQUIVO = "clientes.json"
if os.path.exists(ARQUIVO):
    with open(ARQUIVO, "r", encoding="utf-8") as f:
        clientes = json.load(f)
else:
    clientes = []

def salvar():
    with open (ARQUIVO, "w", encoding="utf-8") as f:
        json.dump(clientes, f, indent=2, ensure_ascii=False)
    print("✅ Salvo!")

def cadastrar():
    nome = input("Nome: ")
    telefone = input("Telefone: ")
    email = input("Email: ")
    clientes.append({"nome": nome, "telefone": telefone, "email": email})
    salvar()
    print("✅ Cliente cadastrado!")

def listar():
    if not clientes:
        print("Nenhum cliente cadastrado.")
        return
    for i, c in enumerate(clientes):
        print(f"{i} - {c['nome']} | {c['telefone']} | {c['email']}")

def editar():
    listar()
    if not clientes:
        return
    try:
        indice = int(input("Qual o número do cliente que quer editar? "))
        if indice <0 or indice >= len(clientes):
            print("❌ Número inválido!")
            return
    except:
        print("❌ Digite só o número!")
        return

    print(f"\nEditando: {clientes[indice]['nome']}")
    print("Se não quiser mudar, É só apertar Enter e deixar em branco!")

    novo_nome = input(f"Novo nome [{clientes[indice]['nome']}]: ")
    novo_tel = input(f"Novo telefone [{clientes[indice]['telefone']}]: ")
    novo_email = input(f"Novo email [{clientes[indice]['email']}]: ")

    if novo_nome != "":
        clientes[indice]['nome'] = novo_nome
    if novo_tel != "":
        clientes[indice]['telefone'] = novo_tel
    if novo_email != "":
        clientes[indice]['email'] = novo_email

    salvar()
    print("✅Cliente editado!")

def excluir():
    listar()
    if not clientes:
        return
    indice = int(input("Qual o número para excluir? "))
    del clientes[indice]
    salvar()
    print("✅ Cliente excluído! ")

# MENU PRINCIPAL
while True:
    print("\n--- SISTEMA DIA 9 ---")
    print("1 - Cadastrar")
    print("2 - Listar")
    print("3 - Editar")
    print("4 - Excluir")
    print("5 - Sair")
    opcao = input("Escolha: ")

    if opcao == "1":
        cadastrar()
    elif opcao == "2":
        listar()
    elif opcao == "3":
        editar()
    elif opcao == "4":
        excluir()
    elif opcao == "5":
        print("Saindo... Até mais!")
        break
    else:
        print("Opção inválida!")